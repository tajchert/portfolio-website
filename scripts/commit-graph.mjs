// Refresh the commit graph in site/index.html.
// Fetches combined GitHub + GitLab contributions from commitgraph.mtajchert.com
// and writes a static inline SVG between the commit-graph markers, so the page
// itself still makes no external requests. Run: npm run graph
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ACCOUNTS = 'github=tajchert&gitlab=mtajchert';
const SOURCE = 'https://commitgraph.mtajchert.com';
const WEEKS = 53;
const CELL = 10;
const PITCH = 12;
const DAY = 86400000;

const file = fileURLToPath(new URL('../site/index.html', import.meta.url));
const iso = (ms) => new Date(ms).toISOString().slice(0, 10);

async function year(y) {
  const res = await fetch(`${SOURCE}/api/contributions?${ACCOUNTS}&year=${y}`);
  if (!res.ok) throw new Error(`${res.url}: HTTP ${res.status}`);
  return (await res.json()).days;
}

// The window ends today and starts on the Monday 52 weeks before this week's Monday.
const today = Date.parse(iso(Date.now()));
const monday = today - ((new Date(today).getUTCDay() + 6) % 7) * DAY;
const start = monday - (WEEKS - 1) * 7 * DAY;

const thisYear = new Date(today).getUTCFullYear();
const totals = new Map();
for (const d of [...(await year(thisYear - 1)), ...(await year(thisYear))]) totals.set(d.date, d.total);

const days = [];
for (let t = start; t <= today; t += DAY) days.push({ t, total: totals.get(iso(t)) ?? 0 });

// Levels 1-4 are quartiles of the active days, so one huge day does not flatten the rest.
const active = days.map((d) => d.total).filter(Boolean).sort((a, b) => a - b);
if (!active.length) throw new Error('No contributions returned; leaving the page unchanged.');
const cuts = [0.25, 0.5, 0.75].map((q) => active[Math.floor(q * (active.length - 1))]);
const level = (n) => (n ? 1 + cuts.filter((c) => n > c).length : 0);

const paths = ['', '', '', '', ''];
for (const d of days) {
  const i = Math.round((d.t - start) / DAY);
  paths[level(d.total)] += `M${Math.floor(i / 7) * PITCH} ${(i % 7) * PITCH}h${CELL}v${CELL}h-${CELL}z`;
}

const sum = active.reduce((a, b) => a + b, 0).toLocaleString('en-US');
const asOf = new Date(today).toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
const width = WEEKS * PITCH - (PITCH - CELL);
const height = 7 * PITCH - (PITCH - CELL);
const label = `Commit graph: ${sum} contributions on GitHub and GitLab in the last 12 months, on ${active.length} days.`;

const block = `<!-- commit-graph:start (generated by npm run graph) -->
  <figure class="graph">
    <svg viewBox="0 0 ${width} ${height}" role="img" aria-label="${label}">
${paths.map((d, i) => (d ? `      <path class="g${i}" d="${d}"/>` : '')).filter(Boolean).join('\n')}
    </svg>
    <figcaption class="m">${sum} contributions on GitHub and GitLab in the last 12 months, on ${active.length} days | as of ${asOf} | <a href="${SOURCE}/?${ACCOUNTS.replace('&', '&amp;')}">live graph</a></figcaption>
  </figure>
  <!-- commit-graph:end -->`;

const html = readFileSync(file, 'utf8');
const marked = /<!-- commit-graph:start[\s\S]*?<!-- commit-graph:end -->/;
if (!marked.test(html)) throw new Error('commit-graph markers not found in site/index.html');
writeFileSync(file, html.replace(marked, () => block));
console.log(`Commit graph updated: ${sum} contributions on ${active.length} days, as of ${asOf}.`);
